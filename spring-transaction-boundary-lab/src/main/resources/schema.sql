-- ============================================================================
-- Q021-EXT 事务边界实验室 建表脚本（H2 内存库）
-- 说明：H2 原生支持标准 SQL 的 COMMENT ON 语法，用于给表/列加中文注释
-- ============================================================================

-- 订单表：核心实验中第一张被 UPDATE 的表
CREATE TABLE IF NOT EXISTS orders (
    id         BIGINT       PRIMARY KEY,
    status     VARCHAR(32)  NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE  orders           IS '订单表（事务实验中先被 UPDATE 的表）';
COMMENT ON COLUMN orders.id        IS '订单 ID（主键）';
COMMENT ON COLUMN orders.status    IS '订单状态：PENDING 待支付 / PAID 已支付';
COMMENT ON COLUMN orders.created_at IS '创建时间';

-- 审计日志表：核心实验中第二张被 INSERT 的表（内层 REQUIRED 事务里写入）
CREATE TABLE IF NOT EXISTS audit_log (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT       NOT NULL,
    action     VARCHAR(64)  NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE  audit_log            IS '审计日志表（内层事务中写入，用于观察 rollback-only 与真实回滚）';
COMMENT ON COLUMN audit_log.id         IS '审计记录 ID（自增主键）';
COMMENT ON COLUMN audit_log.order_id   IS '关联的订单 ID';
COMMENT ON COLUMN audit_log.action     IS '操作名称，例如 PAY_AUDIT';
COMMENT ON COLUMN audit_log.created_at IS '创建时间';
