-- H2 内存库建表（MySQL 兼容模式）。克隆即跑，无需手动建表。
CREATE TABLE IF NOT EXISTS product (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128) NOT NULL,
    price       DECIMAL(10, 2) NOT NULL DEFAULT 0,
    description VARCHAR(512),
    stock       INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS app_user (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password VARCHAR(128) NOT NULL,
    nickname VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS stock (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL,
    count       INT NOT NULL DEFAULT 0
);

-- ===== 场景11 秒杀库存：异步落单归档表 =====
-- (product_id, user_id) 唯一约束 = 用户维度限购的数据库层兜底，
-- 即使 Redis 侧有缝隙也不会出现「同一用户抢到两件」或超卖。
CREATE TABLE IF NOT EXISTS seckill_order (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL,
    user_id     VARCHAR(64) NOT NULL,
    create_time BIGINT,
    CONSTRAINT uk_seckill_product_user UNIQUE (product_id, user_id)
);

-- ===== 场景12 幂等处理：业务去重表 =====
-- biz_id 唯一索引是幂等的最后一道防线：Redis token 只挡「同一 token」，
-- 唯一索引还能挡「不同 token 但同一业务单号」的重复提交。
CREATE TABLE IF NOT EXISTS idempotent_record (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_id      VARCHAR(64) NOT NULL UNIQUE,
    token       VARCHAR(64),
    amount      DECIMAL(10, 2),
    create_time BIGINT
);

-- ===== 场景14 延迟队列：订单状态归档表 =====
-- 订单实时状态存 Redis Hash（delayqueue:order:<id>），DB 仅做关单/支付后的归档，
-- 便于前端查询「历史订单」与统计，也演示 Redis + MySQL 的分工。
CREATE TABLE IF NOT EXISTS delay_order (
    id          VARCHAR(64) PRIMARY KEY,
    user_id     VARCHAR(64),
    state       VARCHAR(16),
    created_at  BIGINT,
    expire_at   BIGINT,
    closed_at   BIGINT
);
